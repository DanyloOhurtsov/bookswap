/**
 * Чи виконує застосунок фонову роботу за власним розкладом.
 *
 * Три сервіси — `NotificationDispatcher` (§7.3), `NotificationDigestService`
 * (§7.5) і `SessionCleanupService` (§6.1) — прокидаються самі: за таймером і,
 * два з них, ще й від поштовху `wake()`. У проді це саме те, що треба. В e2e це
 * єдине джерело недетермінізму, яке неможливо прибрати з боку тесту: усі 35
 * файлів ділять одну базу й один процес, а `claim()`/`reap()` диспетчера
 * фільтрують чергу за `status`/`nextAttemptAt`/`attempts` — глобально, без
 * жодної прив'язки до того, чий це файл. Тож будь-який файл, чий тик збігся з
 * чужим, підбирає й ретраїть чужі доставки.
 *
 * DI-токен, а не змінна оточення: обґрунтування в `notifications.constants.ts` і
 * `auth.constants.ts` («кожен новий env-ключ — це ще один спосіб зламати прод
 * одруківкою») лишається чинним, і цей перемикач його не порушує — прод його не
 * бачить узагалі. Прецедент той самий, що й `AUTH_SHUTDOWN_TIMEOUT`: токен існує
 * рівно заради того, щоб тест міг підставити інше значення, не підміняючи час і
 * не переписуючи код, який працює в проді.
 *
 * Значення за замовчуванням — `'enabled'`, і воно єдине, яке коли-небудь бачить
 * `main.ts`.
 */
export type BackgroundMode = 'enabled' | 'disabled'

/** DI-токен режиму. Провайдиться в `NotificationsModule` і `AuthModule`. */
export const BACKGROUND_MODE = Symbol('BACKGROUND_MODE')

/** Прод-значення. Окремою константою — щоб модулі не писали літерал двічі. */
export const DEFAULT_BACKGROUND_MODE: BackgroundMode = 'enabled'
