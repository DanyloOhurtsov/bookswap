/**
 * Розпізнавання помилок Prisma за кодом.
 *
 * Живе окремо, бо на це спираються дві незалежні речі: реєстрація (зайнятий email)
 * і створення дружби (гонка двох `INSERT` на ту саму пару). Обидві мусять читати
 * той самий код; дві копії розійшлися б при першій же зміні версії Prisma.
 *
 * Перевірка структурна, а не `instanceof`: типи помилок живуть у згенерованому
 * клієнті, і залежність від його внутрішньої структури дорожча за перевірку поля.
 */
export function isUniqueViolation(error: unknown): boolean {
  return typeof error === 'object' && error !== null && 'code' in error && error.code === 'P2002'
}
