import type { Channel } from '@bookswap/shared'

/**
 * §7.3: «Канал не має знати про лоани».
 *
 * Тому сюди приїжджає вже готовий текст і вже обчислений адресат — канал уміє
 * рівно одне: віддати рядки у свій транспорт. Додавання четвертого каналу не
 * торкається ні стейт-машини §5, ні диспетчера: це ще одна реалізація цього
 * інтерфейсу в списку провайдерів.
 */

/**
 * Інлайн-кнопка (§7.4).
 *
 * Живе в спільному повідомленні, а не в Telegram-специфічному типі, бо рішення
 * «у цієї події є дія, яку можна зробити з повідомлення» ухвалює рендерер, а не
 * транспорт. Канали, що кнопок не вміють, просто їх ігнорують — і саме тому
 * `body` мусить лишатися осмисленим без них.
 */
export interface DeliveryAction {
  label: string
  /** Значення `callback_data`. Telegram обмежує його 64 байтами. */
  data: string
}

export interface RenderedNotification {
  subject: string
  body: string
  actions: readonly DeliveryAction[]
}

/**
 * Кому надсилаємо. Читається один раз диспетчером — канал у базу не ходить.
 */
export interface DeliveryRecipient {
  userId: string
  email: string
  /**
   * §6.1: адресу підтверджено.
   *
   * Рядки доставки на непідтверджену адресу взагалі не створюються
   * (`channelsFor`), але між створенням рядка й спробою людина може змінити
   * пошту — і тоді канал мусить відмовитися сам, а не надіслати листа туди, де
   * ніхто не довів, що читає його саме адресат.
   */
  emailVerified: boolean
  /** `null` означає «Telegram не прив'язаний», а не «надішли пізніше». */
  telegramChatId: string | null
}

/**
 * Помилка каналу.
 *
 * `send` **кидає** при невдачі, а не повертає результат: диспетчер однаково
 * мусить ловити все, що прилетить із мережевого виклику, і другий спосіб
 * повідомити про збій означав би два шляхи обробки замість одного.
 */
export interface NotificationChannelSender {
  readonly channel: Channel
  /**
   * `deliveryId` — ключ ідемпотентності на межі з провайдером, там, де провайдер
   * це підтримує (Resend приймає `Idempotency-Key`). Це не робить доставку
   * exactly-once: `Promise.race` у диспетчері не скасовує вже запущений мережевий
   * виклик, тож after-timeout виклик і повторна спроба іншого воркера можуть
   * реально статися обидва. Ключ лише дає провайдеру шанс розпізнати другий
   * виклик як повтор першого й не надіслати вдруге — там, де сам провайдер це
   * вміє. Канали без такої підтримки (Telegram, dev-заглушка) його ігнорують.
   */
  send(
    recipient: DeliveryRecipient,
    message: RenderedNotification,
    deliveryId: string,
  ): Promise<void>
}

/** DI-токен для списку всіх каналів: інтерфейсу в рантаймі не існує. */
export const NOTIFICATION_CHANNELS = 'NOTIFICATION_CHANNELS'
