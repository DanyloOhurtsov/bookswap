/**
 * Числа §7.3 і §7.4.
 *
 * Константами, а не змінними оточення — з тієї самої причини, що й TTL у
 * `auth.constants.ts`: кожен новий env-ключ це ще один спосіб зламати прод
 * одруківкою, а нічого середовищезалежного тут немає. Диспетчер має поводитися
 * однаково на ноуті й на сервері, інакше «в мене не відтворюється» стає
 * властивістю конфігурації.
 */

/** §7.3, правило 2: «Воркер раз на 30 секунд». */
export const DISPATCH_INTERVAL_MS = 30_000

/** §7.3, правило 2: «Після 5 спроб — `FAILED`». */
export const MAX_DELIVERY_ATTEMPTS = 5

/**
 * База експоненційної затримки: 1-ша невдача → 30 с, 2-га → 1 хв, 3-тя → 2 хв,
 * 4-та → 4 хв. П'ятої затримки не існує — після неї рядок стає `FAILED`.
 */
export const DELIVERY_BACKOFF_BASE_MS = 30_000

/** Стеля затримки. Без неї 10-та спроба чекала б добу, а спроб усього 5. */
export const DELIVERY_BACKOFF_MAX_MS = 15 * 60_000

/**
 * Скільки рядків диспетчер обробляє за один тик.
 *
 * Обмеження існує не через навантаження (§1: десятки користувачів), а щоб один
 * тик мав передбачувану тривалість: канали ходять у мережу послідовно, і партія
 * без стелі перетворила б збій провайдера на тик, який не закінчується.
 *
 * Рядки при цьому захоплюються **по одному**, а не пачкою — див. `DELIVERY_LEASE_MS`.
 */
export const DISPATCH_BATCH_SIZE = 25

/**
 * Стеля тривалості однієї спроби.
 *
 * Диспетчер обгортає `send()` цим таймаутом сам, не покладаючись на таймаути
 * всередині каналів. Безпосередньо перед зовнішнім викликом оренда атомарно
 * перевіряється й продовжується; ця межа обмежує очікування вже ПІСЛЯ renew, але
 * не стверджує, що початкова оренда гарантовано покриває довільний `load()` або
 * фінальний запис результату.
 */
export const DELIVERY_ATTEMPT_TIMEOUT_MS = 10_000

/**
 * Оренда захопленого рядка.
 *
 * Рядки захоплюються **по одному**, а безпосередньо перед `send()` оренда
 * перевіряється й поновлюється тим самим fencing-токеном. Шестиразовий запас
 * стосується обмеженого провайдерського виклику після цього renew; `load()` до
 * нього може тривати довше, і тоді pre-send fence відмовить без зовнішнього
 * ефекту. Фінальний запис окремо захищений умовою на fencing-токен.
 *
 * Пачкове захоплення (25 рядків однією орендою) цю властивість ламає: 25 × 10 с
 * не вміщаються в жодну розумну оренду, тож останні рядки партії надсилалися б
 * уже після її кінця — коли той самий рядок міг захопити інший процес. Саме тому
 * захоплення тут поштучне, попри те, що воно дорожче за запитами.
 */
export const DELIVERY_LEASE_MS = 6 * DELIVERY_ATTEMPT_TIMEOUT_MS

/**
 * §7.4: «TTL 10 хвилин».
 *
 * Токен їде в deep link і гаситься першим натисканням Start, тож вікно вузьке
 * навмисно: це секрет, який людина щойно попросила й використовує одразу.
 */
export const TELEGRAM_LINK_TTL_MS = 10 * 60_000

/** §7.5: `LOAN_DUE_SOON` — «за 3 дні до `dueAt`». */
export const DUE_SOON_WINDOW_DAYS = 3

/**
 * Як часто прокидається щоденна задача (§7.5).
 *
 * Щогодини, а не раз на добу, і це не суперечність: задача **ідемпотентна** за
 * ключем «користувач × тип × UTC-доба». `LOAN_DUE_SOON` має один тригерний день,
 * а тривалий `LOAN_OVERDUE` може дати один агрегований дайджест на наступну добу.
 * Тик раз на 24 години означав би, що будь-який перезапуск процесу зсуває
 * розсилку на випадковий час, а перезапуск раз на день скасовує її зовсім.
 */
export const DIGEST_INTERVAL_MS = 60 * 60_000
