import { createHash, randomBytes } from 'node:crypto'

/** 256 біт ентропії. Перебрати неможливо, тож геш може бути швидким. */
const TOKEN_BYTES = 32

/**
 * Одноразові секрети: токен сесії, підтвердження пошти, скидання пароля.
 *
 * Сирий токен віддається користувачеві (в кукі або в листі) і більше ніде не
 * зберігається — у базу йде лише SHA-256 від нього. Тому дамп таблиці `Session`
 * не дає можливості видати себе за когось: із гешу токен не відновити.
 *
 * Повільний KDF (як для паролів) тут був би помилкою в обидва боки: він нічого не
 * додає проти перебору 256-бітного випадкового значення, зате перетворив би
 * перевірку кукі — операцію на КОЖЕН запит — на 100 мс роботи процесора.
 */
export function generateToken(): string {
  // base64url, бо токен їде в кукі та в посиланні з листа: ні `+`, ні `/`, ні `=`
  // там не потрібні, а екранування посилання — це зайвий шанс зіпсувати токен.
  return randomBytes(TOKEN_BYTES).toString('base64url')
}

export function hashToken(token: string): string {
  return createHash('sha256').update(token).digest('hex')
}
