/**
 * Годинник бюджету зупинки. У проді — `Date.now`; у тестах — лічильник, яким
 * керує сам тест.
 *
 * Існує рівно заради цієї підміни: арифметику спільного дедлайну треба вміти
 * перевіряти без wall-clock, інакше твердження «друга фаза не отримує свіжу
 * повну стелю» доводиться вимірюванням реальних затримок на CI — а це вже
 * властивість машини, а не коду.
 */
export type Clock = () => number

/**
 * Один абсолютний дедлайн graceful shutdown і залишок від нього.
 *
 * Правило «бюджет один на ВСІ фази разом» цілком живе у двох рядках нижче:
 * дедлайн рахується один раз у конструкторі, а фаза бере лише `remainingMs()`.
 * Винесено в окремий об'єкт саме тому, що ці два рядки — єдине, що тут узагалі
 * можна перевірити детерміновано: `AuthService` більше не повторює обчислення в
 * себе, тож e2e лишається smoke'ом («прод-шлях справді користується цим
 * об'єктом»), а самі числа доводять unit-тести з фейковим годинником.
 */
export class ShutdownBudget {
  /**
   * Момент, після якого чекати вже нема чого. Рахується **один раз**, на старті
   * зупинки, — у цьому вся суть спільного дедлайну.
   */
  readonly deadlineAt: number

  constructor(
    /** Повний бюджет, з якого рахувався дедлайн. Фаза його ніколи не отримує заново. */
    readonly totalMs: number,
    private readonly now: Clock = () => Date.now(),
  ) {
    this.deadlineAt = now() + totalMs
  }

  /**
   * Скільки від СПІЛЬНОГО бюджету лишилося цієї миті.
   *
   * Ніколи не більше за `totalMs` (дедлайн зафіксовано на старті) і ніколи не
   * менше за нуль: від'ємний залишок означав би «почекаємо ще трохи» вже після
   * дедлайну. Нуль тут читається як тайм-аут, а не як «встигли» — саме так його
   * й трактує `AuthService.settle`.
   */
  remainingMs(): number {
    return Math.max(0, this.deadlineAt - this.now())
  }
}
