/**
 * Терміни життя та параметри кукі (§6.1).
 *
 * Константами, а не змінними оточення: кожен новий env-ключ — це ще один спосіб
 * зламати прод одруківкою, а жодне з цих значень не мусить відрізнятися між
 * середовищами. `Secure` — єдиний виняток, він виводиться з NODE_ENV.
 */

const MINUTE = 60 * 1000
const HOUR = 60 * MINUTE
const DAY = 24 * HOUR

/** Місяць. Довше — незручно відкликати, коротше — люди логінитимуться щотижня. */
export const SESSION_TTL_MS = 30 * DAY

/** Доба: лист про підтвердження цілком може почекати до завтра. */
export const EMAIL_VERIFICATION_TTL_MS = DAY

/** Година: скидання пароля робиться тут і зараз, довге вікно лише збільшує ризик. */
export const PASSWORD_RESET_TTL_MS = HOUR

/** Як часто прибирати прострочені сесії й токени. */
export const CLEANUP_INTERVAL_MS = 15 * MINUTE

/**
 * **Загальний** бюджет graceful shutdown для auth — на всі фази разом, а не на
 * кожну окремо.
 *
 * З нього один раз рахується абсолютний дедлайн (`now + AUTH_SHUTDOWN_TIMEOUT_MS`),
 * і кожна наступна фаза отримує лише те, що від нього лишилося. Стеля «на фазу»
 * була б обіцянкою, якої код не тримає: дві фази по 30 секунд — це хвилина
 * очікування там, де і документація, і оркестратор бачать тридцять секунд.
 *
 * Дренаж узагалі обмежений у часі, бо кожна фаза чекає фіксований знімок і
 * завершується структурно сама, але окремий елемент того знімка може зависнути
 * назавжди не з нашої вини — поштовий провайдер, який не відповідає й не рве
 * з'єднання, або запит до БД, що застряг на локу. Без стелі такий один елемент
 * перетворив би `app.close()` на вічне очікування: деплой висить, доки
 * оркестратор не вб'є процес SIGKILL — тобто рівно той сценарій «процес зник
 * посеред роботи», якого весь цей механізм і мав уникнути.
 *
 * Тридцять секунд — свідомо більше за типовий таймаут HTTP-клієнта пошти й
 * помітно менше за типове вікно `terminationGracePeriodSeconds`, тож у нормі
 * стеля не спрацьовує ніколи, а коли спрацьовує — лишає час дописати лог.
 */
export const AUTH_SHUTDOWN_TIMEOUT_MS = 30 * 1000

/**
 * DI-токен того самого бюджету.
 *
 * Потрібен рівно для одного: регресійний тест на вичерпання стелі мусить
 * підставити короткий бюджет, інакше він або чекав би півхвилини, або
 * перевіряв би не той код, що працює в проді (підміна `Date.now()` чи фейкові
 * таймери навколо реального `app.close()` — це вже інша механіка, ніж та, яку
 * тест обіцяє довести).
 */
export const AUTH_SHUTDOWN_TIMEOUT = Symbol('AUTH_SHUTDOWN_TIMEOUT')

/**
 * Ім'я кукі. Префікс `__Host-` навмисно не використовується: він вимагає Secure,
 * а в dev фронт і API ходять по http://localhost.
 */
export const SESSION_COOKIE_NAME = 'bookswap_session'
