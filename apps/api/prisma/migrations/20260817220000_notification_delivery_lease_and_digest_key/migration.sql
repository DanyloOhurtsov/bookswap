-- §7.3, правило 2: fencing-токен оренди доставки.
--
-- «Захопив рядок» і «маю право записати результат» — різні твердження. Воркер,
-- чия оренда протухла, не має права затерти результат того, хто підхопив рядок
-- після нього: свіжий SENT перетворився б на старий PENDING, і лист пішов би
-- втретє. Кожне захоплення виписує НОВИЙ токен, фінальний запис іде з умовою
-- WHERE "leaseToken" = <мій>.
ALTER TABLE "NotificationDelivery" ADD COLUMN     "leaseToken" TEXT,
ADD COLUMN     "leaseUntil" TIMESTAMP(3);

-- §7.5: ключ ідемпотентності щоденного дайджесту, `<userId>:<type>:<YYYY-MM-DD>`.
--
-- Прапорець у пам'яті воркера не заважає двом процесам API одночасно прочитати
-- «сьогодні ще не надсилали» й створити дублікати. Унікальний індекс перекладає
-- це рішення на базу — єдине місце, яке бачать обидва. NULL у негайних подіях
-- одна одній не заважають: у PostgreSQL унікальність на NULL не поширюється.
ALTER TABLE "Notification" ADD COLUMN     "digestKey" TEXT;

CREATE UNIQUE INDEX "Notification_digestKey_key" ON "Notification"("digestKey");
